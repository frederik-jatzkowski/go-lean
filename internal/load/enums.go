const EnumHeader = "// Code generated by go-lean. DO NOT EDIT."

type Enum struct {
	Name     string
	Variants []string
	pos      token.Position
}

func publicName(name string) string {
	for _, first := range name {
		return string(unicode.ToUpper(first)) + name[len(string(first)):]
	}
	return ""
}

func (e Enum) Constructor(variant string) string {
	return publicName(e.Name) + "_" + publicName(variant)
}
func (e Enum) Matcher() string { return "Match" + publicName(e.Name) }

type enumExport struct {
	decl    *ast.FuncDecl
	aliases map[string]string
}

type EnumFile struct {
	Content []byte
}

func discoverEnums(ctx context.Context, dir, pattern string) (map[string][]Enum, map[string]EnumFile, error) {
	roots, err := packages.Load(&packages.Config{Context: ctx, Dir: dir, Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles | packages.NeedImports | packages.NeedDeps | packages.NeedModule}, pattern)
	if err != nil {
		return nil, nil, err
	}
	enums := make(map[string][]Enum)
	files := make(map[string]EnumFile)
	var discoveryErr error
	packages.Visit(roots, func(p *packages.Package) bool {
		if discoveryErr != nil || p.Module == nil || !p.Module.Main || len(p.GoFiles) == 0 {
			return false
		}
		enums[p.PkgPath], discoveryErr = discoverPackageEnums(p, files)
		return discoveryErr == nil
	}, nil)
	return enums, files, discoveryErr
}

func discoverPackageEnums(p *packages.Package, outputs map[string]EnumFile) ([]Enum, error) {
	path := filepath.Join(filepath.Dir(p.GoFiles[0]), "lean.gen.go")
	set := token.NewFileSet()
	var enums []Enum
	var exports []enumExport
	structs := make(map[string]*ast.StructType)
	names := make(map[string]bool)
	imports := make(map[*ast.StructType]map[string]string)
	for _, file := range p.GoFiles {
		if file == path {
			continue
		}
		source, err := parser.ParseFile(set, file, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		parsed, err := enumDirectives(set, source.Doc)
		if err != nil {
			return nil, err
		}
		enums = append(enums, parsed...)
		aliases := make(map[string]string)
		for _, spec := range source.Imports {
			path, err := strconv.Unquote(spec.Path.Value)
			if err != nil {
				return nil, err
			}
			alias := filepath.Base(path)
			if spec.Name != nil {
				alias = spec.Name.Name
			}
			aliases[alias] = spec.Path.Value
		}
		for _, decl := range source.Decls {
			if fn, ok := decl.(*ast.FuncDecl); ok && fn.Doc != nil && fn.Recv == nil && !fn.Name.IsExported() {
				for _, comment := range fn.Doc.List {
					if kind, _, _ := directive(comment.Text); kind == "export" {
						exports = append(exports, enumExport{fn, aliases})
						break
					}
				}
			}
		}
		for name, obj := range source.Scope.Objects {
			names[name] = true
			if spec, ok := obj.Decl.(*ast.TypeSpec); ok && spec.TypeParams == nil && !spec.Assign.IsValid() {
				if record, ok := spec.Type.(*ast.StructType); ok {
					structs[name] = record
					imports[record] = aliases
				}
			}
		}
	}
	managed, exists, err := enumFileStatus(path)
	if err != nil {
		return nil, err
	}
	if len(enums) == 0 {
		if managed {
			outputs[path] = EnumFile{}
		}
		return nil, nil
	}
	if exists && !managed {
		return nil, fmt.Errorf("%s: enum generation would overwrite a handwritten file", path)
	}
	content, err := renderEnums(p.Name, enums, structs, names, imports, exports, set)
	if err != nil {
		return nil, err
	}
	outputs[path] = EnumFile{Content: content}
	return enums, nil
}

func enumFileStatus(path string) (managed, exists bool, err error) {
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return false, false, nil
	}
	if err != nil {
		return false, false, err
	}
	header, _, _ := bytes.Cut(data, []byte("\n"))
	return string(bytes.TrimSuffix(header, []byte("\r"))) == EnumHeader, true, nil
}

func enumDirectives(set *token.FileSet, doc *ast.CommentGroup) ([]Enum, error) {
	if doc == nil {
		return nil, nil
	}
	var result []Enum
	for i := 0; i < len(doc.List); i++ {
		comment := doc.List[i]
		kind, value, _ := directive(comment.Text)
		if kind == "generate:enum+" {
			return nil, fmt.Errorf("%s: enum continuation requires an enum directive", set.Position(comment.Pos()))
		}
		if kind != "generate:enum" {
			continue
		}
		for i+1 < len(doc.List) {
			next, continuation, _ := directive(doc.List[i+1].Text)
			if next != "generate:enum+" {
				break
			}
			value += " " + continuation
			i++
		}
		name, body, open := strings.Cut(value, "{")
		body, closed := strings.CutSuffix(strings.TrimSpace(body), "}")
		name = strings.TrimSpace(name)
		if !open || !closed || !token.IsIdentifier(name) || ast.IsExported(name) || !ast.IsExported(publicName(name)) {
			return nil, fmt.Errorf("%s: expected a private enum name followed by { variants }", set.Position(comment.Pos()))
		}
		entry := Enum{Name: name, pos: set.Position(comment.Pos())}
		for _, raw := range strings.Split(strings.TrimSuffix(strings.TrimSpace(body), ","), ",") {
			variant := strings.TrimSpace(raw)
			if !token.IsIdentifier(variant) || ast.IsExported(variant) || !ast.IsExported(publicName(variant)) {
				return nil, fmt.Errorf("%s: expected a private variant name", set.Position(comment.Pos()))
			}
			entry.Variants = append(entry.Variants, variant)
		}
		result = append(result, entry)
	}
	return result, nil
}

func renderEnums(pkg string, enums []Enum, structs map[string]*ast.StructType, names map[string]bool, imports map[*ast.StructType]map[string]string, exports []enumExport, set *token.FileSet) ([]byte, error) {
	var out bytes.Buffer
	usedImports := map[string]string{"goleanreflect": "\"reflect\""}
	used := make(map[string]bool)
	for _, e := range enums {
		for _, name := range append([]string{e.Name, e.Matcher(), e.Name + "Variant"}, constructorNames(e)...) {
			if names[name] {
				return nil, fmt.Errorf("%s: enum identifier %s is already declared", e.pos, name)
			}
			names[name] = true
		}
		fmt.Fprintf(&out, "type %s struct { variant %sVariant }\ntype %sVariant interface { is%s() }\n", e.Name, e.Name, e.Name, publicName(e.Name))
		for _, variant := range e.Variants {
			record := structs[variant]
			if record == nil || used[variant] {
				return nil, fmt.Errorf("%s: %s must be a unique package-local nongeneric variant struct", e.pos, variant)
			}
			used[variant] = true
			fmt.Fprintf(&out, "func (%s) is%s() {}\n", variant, publicName(e.Name))
			var params, fields []string
			for _, field := range record.Fields.List {
				if len(field.Names) == 0 {
					return nil, fmt.Errorf("%s: variant fields must be named", set.Position(field.Pos()))
				}
				typeText, err := enumTypeText(set, field.Type, imports[record], usedImports)
				if err != nil {
					return nil, err
				}
				for _, name := range field.Names {
					if ast.IsExported(name.Name) || name.Name == "_" {
						return nil, fmt.Errorf("%s: variant fields must be private", set.Position(name.Pos()))
					}
					param := fmt.Sprintf("_goleanValue%d", len(params))
					params = append(params, param+" "+typeText)
					fields = append(fields, name.Name+": "+param)
				}
			}
			fmt.Fprintf(&out, "func %s(%s) %s {\n", e.Constructor(variant), strings.Join(params, ", "), e.Name)
			for i := range params {
				fmt.Fprintf(&out, "goleanCheckEnumInput(_goleanValue%d)\n", i)
			}
			fmt.Fprintf(&out, "return %s{variant: %s{%s}}\n}\n", e.Name, variant, strings.Join(fields, ", "))
		}
		fmt.Fprintf(&out, "func %s[R any](_goleanTarget %s", e.Matcher(), e.Name)
		for i, variant := range e.Variants {
			fmt.Fprintf(&out, ", _goleanCase%d func(%s) R", i, variant)
		}
		fmt.Fprintln(&out, ") R { switch v := _goleanTarget.variant.(type) {")
		for i, variant := range e.Variants {
			fmt.Fprintf(&out, "case %s: return _goleanCase%d(v)\n", variant, i)
		}
		fmt.Fprintln(&out, "default: panic(\"golean: invalid enum value\")\n} }")
	}
	for _, export := range exports {
		fn := export.decl
		public := publicName(fn.Name.Name)
		if names[public] {
			return nil, fmt.Errorf("%s: enum export %s collides with an existing declaration", set.Position(fn.Pos()), public)
		}
		names[public] = true
		if fn.Type.TypeParams != nil || fn.Type.Results == nil || len(fn.Type.Results.List) != 1 {
			return nil, fmt.Errorf("enum export %s requires one result and no type parameters", public)
		}
		result, err := enumTypeText(set, fn.Type.Results.List[0].Type, export.aliases, usedImports)
		if err != nil {
			return nil, err
		}
		var params, args []string
		for _, field := range fn.Type.Params.List {
			if _, variadic := field.Type.(*ast.Ellipsis); variadic {
				return nil, fmt.Errorf("enum export %s cannot be variadic", public)
			}
			typ, err := enumTypeText(set, field.Type, export.aliases, usedImports)
			if err != nil {
				return nil, err
			}
			for range max(1, len(field.Names)) {
				arg := fmt.Sprintf("_goleanValue%d", len(args))
				args = append(args, arg)
				params = append(params, arg+" "+typ)
			}
		}
		fmt.Fprintf(&out, "func %s(%s) %s {\n", public, strings.Join(params, ", "), result)
		for _, arg := range args {
			fmt.Fprintf(&out, "goleanCheckEnumInput(%s)\n", arg)
		}
		fmt.Fprintf(&out, "return %s(%s)\n}\n", fn.Name.Name, strings.Join(args, ", "))
	}
	fmt.Fprintln(&out, `func goleanCheckEnumInput(value any) {
	input := goleanreflect.ValueOf(value)
	if input.IsValid() && goleanContainsEnum(input.Type(), make(map[goleanreflect.Type]bool)) {
		goleanCheckEnumValue(input)
	}
}

func goleanIsEnum(typ goleanreflect.Type) bool {
	return typ.Kind() == goleanreflect.Struct && typ.NumField() == 1 &&
		typ.Field(0).Name == "variant" && typ.Field(0).Type.Kind() == goleanreflect.Interface
}

func goleanContainsEnum(typ goleanreflect.Type, seen map[goleanreflect.Type]bool) bool {
	if seen[typ] {
		return false
	}
	seen[typ] = true
	switch typ.Kind() {
	case goleanreflect.Struct:
		if goleanIsEnum(typ) {
			return true
		}
		for i := 0; i < typ.NumField(); i++ {
			if goleanContainsEnum(typ.Field(i).Type, seen) {
				return true
			}
		}
	case goleanreflect.Array, goleanreflect.Slice, goleanreflect.Pointer:
		return goleanContainsEnum(typ.Elem(), seen)
	}
	return false
}

func goleanCheckEnumValue(value goleanreflect.Value) {
	switch value.Kind() {
	case goleanreflect.Struct:
		if goleanIsEnum(value.Type()) {
			if value.Field(0).IsNil() {
				panic("golean: invalid enum value")
			}
			return
		}
		for i := 0; i < value.NumField(); i++ {
			goleanCheckEnumValue(value.Field(i))
		}
	case goleanreflect.Array, goleanreflect.Slice:
		for i := 0; i < value.Len(); i++ {
			goleanCheckEnumValue(value.Index(i))
		}
	case goleanreflect.Pointer:
		goleanCheckEnumValue(value.Elem())
	}
}`)
	var generated bytes.Buffer
	fmt.Fprintf(&generated, "%s\n\npackage %s\n", EnumHeader, pkg)
	var aliases []string
	for alias := range usedImports {
		aliases = append(aliases, alias)
	}
	slices.Sort(aliases)
	for _, alias := range aliases {
		fmt.Fprintf(&generated, "import %s %s\n", alias, usedImports[alias])
	}
	generated.Write(out.Bytes())
	return format.Source(generated.Bytes())
}

func constructorNames(e Enum) []string {
	result := make([]string, 0, len(e.Variants))
	for _, variant := range e.Variants {
		result = append(result, e.Constructor(variant))
	}
	return result
}

func enumTypeText(set *token.FileSet, typ ast.Expr, aliases, used map[string]string) (string, error) {
	var conflict string
	ast.Inspect(typ, func(node ast.Node) bool {
		if selector, ok := node.(*ast.SelectorExpr); ok {
			if id, ok := selector.X.(*ast.Ident); ok && aliases[id.Name] != "" {
				path := aliases[id.Name]
				if current := used[id.Name]; current != "" && current != path {
					conflict = id.Name
				}
				used[id.Name] = path
			}
		}
		return true
	})
	if conflict != "" {
		return "", fmt.Errorf("conflicting import name %s in enum payload", conflict)
	}
	var typeText bytes.Buffer
	err := format.Node(&typeText, set, typ)
	return typeText.String(), err
}
