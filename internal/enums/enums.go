package enums

import (
	"bytes"
	"context"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/frederik-jatzkowski/go-lean/internal/genfile"
	"golang.org/x/tools/go/packages"
)

const File = "lean.gen.go"
const header = "// Code generated by go-lean; DO NOT EDIT.\n"
const prefix = "//golean:generate:enum"

type Spec struct {
	Name, Default string
	Cases         []string
}

func (s Spec) Constructor(variant string) string { return "New" + s.Name + variant }

var syntax = regexp.MustCompile(`^\s*([^\s{}]+)\s*\{([^{}]*)\}\s*$`)

func Read(doc *ast.CommentGroup, fset *token.FileSet) ([]Spec, error) {
	var specs []Spec
	if doc == nil {
		return specs, nil
	}
	for _, comment := range doc.List {
		value, ok := strings.CutPrefix(comment.Text, prefix)
		if !ok {
			continue
		}
		match := syntax.FindStringSubmatch(value)
		fail := func(message string) ([]Spec, error) {
			return nil, fmt.Errorf("%s: %s", fset.Position(comment.Pos()), message)
		}
		if match == nil || !validName(match[1]) {
			return fail("expected enum Name { Variant default, OtherVariant }")
		}
		spec := Spec{Name: match[1]}
		seen := make(map[string]bool)
		for _, variant := range strings.Split(match[2], ",") {
			words := strings.Fields(variant)
			if len(words) == 0 || len(words) > 2 || !validName(words[0]) || (len(words) == 2 && words[1] != "default") {
				return fail("invalid enum variant")
			}
			name := words[0]
			if seen[name] {
				return fail("duplicate enum variant " + name)
			}
			seen[name] = true
			spec.Cases = append(spec.Cases, name)
			if len(words) == 2 {
				if spec.Default != "" {
					return fail("enum requires exactly one default variant")
				}
				spec.Default = name
			}
		}
		if spec.Default == "" {
			return fail("enum requires exactly one default variant")
		}
		specs = append(specs, spec)
	}
	return specs, nil
}

func validName(name string) bool { return name != "_" && token.IsIdentifier(name) }

func Render(pkg string, specs []Spec) ([]byte, error) {
	var out strings.Builder
	out.WriteString(header)
	fmt.Fprintf(&out, "\npackage %s\n", pkg)
	for _, spec := range specs {
		receiver := "value"
		for receiver == spec.Name || receiver == spec.Default {
			receiver += "_"
		}
		fmt.Fprintf(&out, "\ntype %s struct {\n _ [0]func()\n payload interface{}\n}\n", spec.Name)
		for _, name := range spec.Cases {
			fmt.Fprintf(&out, "\nfunc %s(%s %s) %s {\n return %s{payload: %s}\n}\n", spec.Constructor(name), receiver, name, spec.Name, spec.Name, receiver)
		}
		empty := "empty"
		if empty == spec.Default {
			empty = "empty_"
		}
		fmt.Fprintf(&out, "\nfunc (%s %s) Case() interface{} {\n var %s interface{}\n if %s.payload == %s {\n var zero %s\n return zero\n }\n return %s.payload\n}\n", receiver, spec.Name, empty, receiver, empty, spec.Default, receiver)
	}
	return format.Source([]byte(out.String()))
}

func Process(ctx context.Context, dir, pattern string, write bool) error {
	roots, err := packages.Load(&packages.Config{Context: ctx, Dir: dir, Mode: packages.NeedName | packages.NeedFiles}, pattern)
	if err != nil {
		return err
	}
	for _, pkg := range roots {
		if len(pkg.Errors) > 0 {
			return pkg.Errors[0]
		}
		if err := generatePackage(pkg, write); err != nil {
			return err
		}
	}
	return nil
}

func generatePackage(pkg *packages.Package, write bool) error {
	if len(pkg.GoFiles) == 0 {
		return nil
	}
	paths := append([]string(nil), pkg.GoFiles...)
	sort.Strings(paths)
	var specs []Spec
	names := make(map[string]bool)
	defined := make(map[string]bool)
	fset := token.NewFileSet()
	output := filepath.Join(filepath.Dir(paths[0]), File)
	for _, path := range paths {
		if filepath.Base(path) == File {
			continue
		}
		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments|parser.SkipObjectResolution)
		if err != nil {
			return err
		}
		found, err := Read(file.Doc, fset)
		if err != nil {
			return err
		}
		specs = append(specs, found...)
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil {
					names[d.Name.Name] = true
				}
			case *ast.GenDecl:
				for _, s := range d.Specs {
					switch s := s.(type) {
					case *ast.TypeSpec:
						names[s.Name.Name] = true
						defined[s.Name.Name] = !s.Assign.IsValid() && s.TypeParams == nil
					case *ast.ValueSpec:
						for _, name := range s.Names {
							names[name.Name] = true
						}
					}
				}
			}
		}
	}
	old, err := os.ReadFile(output)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if len(specs) == 0 {
		if !Owns(old) {
			return nil
		}
		if !write {
			return Stale(output)
		}
		return os.Remove(output)
	}
	if old != nil && !Owns(old) {
		return fmt.Errorf("%s is reserved for go-lean generated code in this package", output)
	}
	// Validate payloads before reserving generated names.
	for _, spec := range specs {
		for _, name := range spec.Cases {
			if !defined[name] {
				return fmt.Errorf("%s: %s requires a package-local defined payload type %s", output, spec.Name, name)
			}
		}
	}
	for _, spec := range specs {
		for _, name := range append([]string{spec.Name}, constructorNames(spec)...) {
			if names[name] {
				return fmt.Errorf("%s: generated enum declaration %s collides with another declaration", output, name)
			}
			names[name] = true
		}
	}
	data, err := Render(pkg.Name, specs)
	if err != nil {
		return err
	}
	if Matches(old, data) {
		return nil
	}
	if !write {
		return Stale(output)
	}
	return genfile.WriteChanged(output, string(data))
}

func constructorNames(spec Spec) []string {
	result := make([]string, 0, len(spec.Cases))
	for _, name := range spec.Cases {
		result = append(result, spec.Constructor(name))
	}
	return result
}

func Stale(path string) error {
	return fmt.Errorf("%s is missing or stale, run go-lean generate for its package", path)
}

func normalize(data []byte) []byte         { return bytes.ReplaceAll(data, []byte("\r\n"), []byte("\n")) }
func Matches(actual, expected []byte) bool { return bytes.Equal(normalize(actual), expected) }

func Owns(data []byte) bool { return bytes.HasPrefix(normalize(data), []byte(header)) }
