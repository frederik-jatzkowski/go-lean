// Package lean renders a validated Go Lean IR program as Lean 4 source.
package lean

import (
	"fmt"
	"strings"

	"github.com/frederik-jatzkowski/go-lean/internal/ir"
)

const GeneratedHeader = "-- Code generated by go-lean. DO NOT EDIT."

func Render(program ir.Program) string {
	var out strings.Builder
	out.WriteString(GeneratedHeader + "\nimport Init\n")
	// Go allows unused parameters, and they are part of the generated signature.
	out.WriteString("\nset_option linter.unusedVariables false\n")
	out.WriteString("\nnamespace GoLean\n")
	for _, fn := range program.Functions {
		fmt.Fprintf(&out, "\ndef %s", symbolName(fn.Symbol))
		for _, param := range fn.Params {
			fmt.Fprintf(&out, " (%s : %s)", binderName(param), param.Type)
		}
		if fn.CanPanic {
			fmt.Fprintf(&out, " : Option %s := do\n", fn.Result)
		} else {
			fmt.Fprintf(&out, " : %s :=\n", fn.Result)
		}
		renderBody(&out, fn.Body, "  ", fn.CanPanic)
	}
	out.WriteString("\nend GoLean\n")
	return out.String()
}

func renderBody(out *strings.Builder, body ir.Body, indent string, canPanic bool) {
	for _, binding := range body.Bindings {
		operator := ":="
		if binding.CanPanic {
			operator = "←"
		}
		fmt.Fprintf(out, "%slet %s : %s %s %s\n", indent, binderName(binding.Binder), binding.Binder.Type, operator, renderExpr(binding.Value))
	}
	switch result := body.Result.(type) {
	case ir.Return:
		out.WriteString(indent)
		if canPanic {
			out.WriteString("return ")
		}
		fmt.Fprintln(out, renderExpr(result.Value))
	case ir.If:
		fmt.Fprintf(out, "%sif %s then\n", indent, renderExpr(result.Condition))
		renderBody(out, result.Then, indent+"  ", canPanic)
		fmt.Fprintf(out, "%selse\n", indent)
		renderBody(out, result.Else, indent+"  ", canPanic)
	default:
		panic("unexpected IR result")
	}
}

func renderExpr(expr ir.Expr) string {
	switch expr := expr.(type) {
	case ir.IntLiteral:
		if expr.Type.IsUnsigned() {
			return fmt.Sprintf("(%s.ofNat (%s))", expr.Type, expr.Value)
		}
		return fmt.Sprintf("(%s.ofInt (%s))", expr.Type, expr.Value)
	case ir.BoolLiteral:
		if expr {
			return "true"
		}
		return "false"
	case ir.Ref:
		return binderName(ir.Binder(expr))
	case ir.Negate:
		return "(-" + renderExpr(expr.Value) + ")"
	case ir.Not:
		return "(!" + renderExpr(expr.Value) + ")"
	case ir.Binary:
		left, right := renderExpr(expr.Left), renderExpr(expr.Right)
		if expr.Op == ir.Divide {
			if expr.OperandType.IsUnsigned() {
				return fmt.Sprintf("if %s = 0 then none else some (%s / %s)", right, left, right)
			}
			return fmt.Sprintf("if %s = 0 then none else some (%s.ofInt ((%s).toInt.tdiv (%s).toInt))", right, expr.OperandType, left, right)
		}
		value := fmt.Sprintf("(%s %s %s)", left, operators[expr.Op], right)
		if expr.Op >= ir.Equal {
			return "(decide " + value + ")"
		}
		return value
	case ir.Call:
		call := "_root_.GoLean." + symbolName(expr.Callee)
		if len(expr.Args) == 0 {
			return call
		}
		args := []string{call}
		for _, arg := range expr.Args {
			args = append(args, renderExpr(arg))
		}
		return "(" + strings.Join(args, " ") + ")"
	default:
		panic("unexpected IR expression")
	}
}

var operators = [...]string{
	ir.Add:          "+",
	ir.Subtract:     "-",
	ir.Multiply:     "*",
	ir.Equal:        "=",
	ir.NotEqual:     "≠",
	ir.Less:         "<",
	ir.LessEqual:    "≤",
	ir.Greater:      ">",
	ir.GreaterEqual: "≥",
}

func quoted(name string) string { return "«" + name + "»" }

func symbolName(symbol ir.Symbol) string {
	name := quoted(symbol.Package) + "." + quoted(symbol.File)
	if symbol.Dependency != "" {
		name += ".Dependencies." + quoted(symbol.Dependency)
	}
	return name + "." + quoted(symbol.Name)
}

func binderName(binder ir.Binder) string {
	return quoted(fmt.Sprintf("v%d_%s", binder.Index, binder.Name))
}
