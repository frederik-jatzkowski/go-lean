// Package emit renders typed IR as Lean package artifacts.
package emit

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/frederik-jatzkowski/go-lean/internal/core/ir"
	"github.com/frederik-jatzkowski/go-lean/pkg/lean"
)

const GeneratedHeader = "-- Code generated by go-lean. DO NOT EDIT."

const generated = GeneratedHeader + "\n"

type Artifact struct {
	Stem, Content string
	// Preserve keeps an existing handwritten companion untouched.
	Preserve bool
}

type renderer struct {
	word          string
	foldNamespace string
	measured      bool
	self          ir.Symbol
}

func identifier(name string) string { return "«" + name + "»" }

func Module(relativeDir, stem string) string {
	parts := []string{stem}
	if relativeDir != "." {
		parts = append(strings.Split(relativeDir, "/"), stem)
	}
	for i, part := range parts {
		parts[i] = identifier(part)
	}
	return strings.Join(parts, ".")
}

func Render(p *ir.Package, modules map[string]string) []Artifact {
	r := renderer{word: scalar[p.Word], foldNamespace: "_root_." + namespace(p.Path) + ".«fold»"}
	model := p.Name
	artifacts := []Artifact{{Stem: model, Content: r.model(p, modules)}}
	if p.Laws.IsEmpty() {
		return artifacts
	}
	proofs, verify := p.Name+"_proofs", p.Name+"_verify"
	moduleStem := func(stem string) string {
		return strings.TrimSuffix(modules[p.Path], identifier(model)) + identifier(stem)
	}
	return append(artifacts,
		Artifact{Stem: proofs, Content: r.scaffold(p, modules[p.Path]), Preserve: true},
		Artifact{Stem: verify, Content: r.verify(p, modules[p.Path], moduleStem(proofs))},
	)
}

func namespace(path string) string { return "GoLean." + identifier(path) }
func qualified(sym ir.Symbol) string {
	return "_root_." + namespace(sym.Package) + "." + identifier(sym.Name)
}

func local(id int) string      { return fmt.Sprintf("«local:%d»", id) }
func field(name string) string { return identifier("field:" + name) }
func contractName(caller, callee ir.Symbol) string {
	return identifier("contract:" + caller.Name + ":" + callee.Package + "." + callee.Name)
}
func contractVar(sym ir.Symbol) string {
	return identifier("dependency:" + sym.Package + "." + sym.Name)
}

var scalar = map[ir.Kind]string{
	ir.Bool: "_root_.Bool", ir.String: "(_root_.List _root_.UInt8)",
	ir.Int8: "_root_.Int8", ir.Int16: "_root_.Int16", ir.Int32: "_root_.Int32", ir.Int64: "_root_.Int64",
	ir.UInt8: "_root_.UInt8", ir.UInt16: "_root_.UInt16", ir.UInt32: "_root_.UInt32", ir.UInt64: "_root_.UInt64",
}

func leanType(t ir.Type) string {
	return renderType(t, nil)
}

func reference(t ir.Type) ir.Symbol {
	switch t := t.Case().(type) {
	case ir.RecordType:
		return t.Symbol
	case ir.EnumTypeRef:
		return t.Symbol
	default:
		return ir.Symbol{}
	}
}

func renderType(t ir.Type, mutual map[ir.Symbol]bool) string {
	renderRef := func(symbol ir.Symbol) string {
		if mutual[symbol] {
			return identifier(symbol.Name)
		}
		return qualified(symbol)
	}
	switch t := t.Case().(type) {
	case ir.RecordType:
		return renderRef(t.Symbol)
	case ir.EnumTypeRef:
		return renderRef(t.Symbol)
	case ir.ArrayType:
		return "(_root_.Array " + renderType(t.Element, mutual) + ")"
	case ir.ByteArrayType:
		return "_root_.ByteArray"
	case ir.MapType:
		return "(_root_.Std.TreeMap " + renderType(t.Key, mutual) + " " + renderType(t.Value, mutual) + " _root_.Ord.compare)"
	case ir.SetType:
		return "(_root_.Std.TreeSet " + renderType(t.Key, mutual) + " _root_.Ord.compare)"
	case ir.OptionType:
		return "(_root_.Option " + renderType(t.Element, mutual) + ")"
	case ir.BoxType:
		return "(_root_.Option " + renderType(t.Element, mutual) + ")"
	case ir.ListType:
		return "(_root_.List " + renderType(t.Element, mutual) + ")"
	case ir.FoldControlType:
		return "(_root_.Prod " + renderType(t.Element, mutual) + " _root_.Bool)"
	case ir.BitVecType:
		return "(_root_.Sigma (fun w : {n : _root_.Nat // n ≤ 64} => _root_.BitVec w.val))"
	case ir.ScalarType:
		return scalar[t.Scalar]
	default:
		panic(fmt.Sprintf("unexpected IR type %T", t))
	}
}

func toSlice[T any](values lean.List[T]) []T {
	return lean.FoldList(values, nil, func(value T, result []T) []T {
		return append(result, value)
	})
}

func (r renderer) model(p *ir.Package, modules map[string]string) string {
	var b strings.Builder
	b.WriteString(generated)
	if !p.Laws.IsEmpty() {
		b.WriteString("\n-- Laws for review (formal definitions below the model)\n")
		for _, law := range toSlice(p.Laws) {
			fmt.Fprintf(&b, "--\n-- %s :\n--   %s\n", law.Proposition.Name, strings.ReplaceAll(proposition(law), "\n", "\n--   "))
		}
		b.WriteByte('\n')
	}
	b.WriteString("import Std\n")
	imported := map[string]bool{identifier("Std"): true}
	for _, path := range toSlice(p.Imports) {
		module := modules[path]
		fmt.Fprintln(&b, "import "+module)
		imported[module] = true
	}
	for _, path := range toSlice(p.LeanImports) {
		parts := strings.Split(path, ".")
		for i, part := range parts {
			parts[i] = identifier(part)
		}
		module := strings.Join(parts, ".")
		if !imported[module] {
			fmt.Fprintln(&b, "import "+module)
		}
	}
	fmt.Fprintf(&b, "\nnamespace %s\n", namespace(p.Path))
	r.writeFolds(&b, p.Folds)
	decls := toSlice(p.Decls)
	hasMutual := false
	for _, decl := range decls {
		if _, ok := decl.Case().(ir.Mutual); ok {
			hasMutual = true
			break
		}
	}
	for _, decl := range decls {
		switch d := decl.Case().(type) {
		case ir.Struct:
			writeStruct(&b, d)
		case ir.Enum:
			writeEnum(&b, d, nil)
		case ir.Mutual:
			b.WriteString("\nmutual\n")
			var projections strings.Builder
			members := make(map[ir.Symbol]bool)
			types := toSlice(d.Types)
			for _, typ := range types {
				switch t := typ.Case().(type) {
				case ir.MutualEnum:
					members[t.Enum.Symbol] = true
				case ir.MutualRecord:
					members[t.Record.Symbol] = true
				}
			}
			for _, typ := range types {
				switch t := typ.Case().(type) {
				case ir.MutualEnum:
					writeEnum(&b, t.Enum, members)
				case ir.MutualRecord:
					writeRecordInductive(&b, t.Record, members)
					writeRecordProjections(&projections, t.Record, members)
				}
			}
			b.WriteString("end\n")
			b.WriteString(projections.String())
		case ir.TypeAlias:
			fmt.Fprintf(&b, "\nabbrev %s : Type := %s\n", identifier(d.Symbol.Name), leanType(d.Type))
		case ir.NamedConstant:
			fmt.Fprintf(&b, "\ndef %s : %s := %s\n", identifier(d.Symbol.Name), leanType(d.Value.Type), r.constant(d.Value))
		case ir.Contract:
			fmt.Fprintf(&b, "\nstructure %s where\n  operation : ", contractName(d.Caller, d.Callee))
			for _, t := range toSlice(d.Params) {
				fmt.Fprintf(&b, "%s → ", leanType(t))
			}
			fmt.Fprintln(&b, leanType(d.Result))
			for _, law := range toSlice(d.Assumptions) {
				fmt.Fprintf(&b, "  %s : (let %s := operation;\n    %s)\n", identifier(law.Name), identifier(d.Callee.Name), indent(law.Lean, 4))
			}
		case ir.Function:
			if d.Termination != "" {
				b.WriteString("\nset_option linter.unusedVariables false in\nset_option linter.unusedSimpArgs false in\n")
			}
			fmt.Fprintf(&b, "\ndef %s", identifier(d.Symbol.Name))
			for _, callee := range toSlice(d.Contracts) {
				fmt.Fprintf(&b, " (%s : %s)", contractVar(callee), contractName(d.Symbol, callee))
			}
			for _, param := range toSlice(d.Params) {
				name := local(param.ID)
				if param.Unused {
					name = "_"
				}
				fmt.Fprintf(&b, " (%s : %s)", name, leanType(param.Type))
			}
			body := r
			body.measured = d.Termination != ""
			body.self = d.Symbol
			fmt.Fprintf(&b, " : %s :=\n  %s\n", leanType(d.Result), body.expr(d.Body))
			if body.measured {
				writeTermination(&b, d, hasMutual)
			}
		}
	}
	fmt.Fprintf(&b, "\nend %s\n", namespace(p.Path))
	if !p.Laws.IsEmpty() {
		writeLaws(&b, p)
	}
	return b.String()
}

func indent(value string, n int) string {
	return strings.ReplaceAll(value, "\n", "\n"+strings.Repeat(" ", n))
}

func writeLaws(b *strings.Builder, p *ir.Package) {
	fmt.Fprintf(b, "\nnamespace %s.Laws\n\nset_option autoImplicit false\n", namespace(p.Path))
	for _, law := range toSlice(p.Laws) {
		fmt.Fprintf(b, "\ndef %s : Prop :=\n  %s\n", identifier(law.Proposition.Name), indent(proposition(law), 2))
	}
	fmt.Fprintf(b, "\nend %s.Laws\n", namespace(p.Path))
}

func proposition(law ir.Law) string {
	var b strings.Builder
	for i, callee := range toSlice(law.Contracts) {
		fmt.Fprintf(&b, "∀ (dependency%d : %s),\n", i, contractName(law.Caller, callee))
	}
	b.WriteString(law.Proposition.Lean)
	return b.String()
}

func (r renderer) scaffold(p *ir.Package, model string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "import %s\n\nnamespace %s.Proofs\n", model, namespace(p.Path))
	for _, law := range toSlice(p.Laws) {
		fmt.Fprintf(&b, "\ntheorem %s : Laws.%s := by\n  sorry\n", identifier(law.Proposition.Name), identifier(law.Proposition.Name))
	}
	fmt.Fprintf(&b, "\nend %s.Proofs\n", namespace(p.Path))
	return b.String()
}

func (r renderer) verify(p *ir.Package, model, proofs string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%simport Lean.Elab.Command\nimport Lean.Util.CollectAxioms\nimport %s\nimport %s\n\n", generated, model, proofs)
	b.WriteString(audit)
	for _, law := range toSlice(p.Laws) {
		ns, name := namespace(p.Path), identifier(law.Proposition.Name)
		fmt.Fprintf(&b, "\nrun_cmd auditGoProof `%s `%s.Proofs.%s `%s.Laws.%s\n", proofs, ns, name, ns, name)
		fmt.Fprintf(&b, "theorem %s.Checked.%s : %s.Laws.%s := %s.Proofs.%s\n", ns, name, ns, name, ns, name)
	}
	return b.String()
}

const audit = `private def auditGoProof (companion proof law : Lean.Name) : Lean.Elab.Command.CommandElabM Unit := do
  let env ← Lean.getEnv
  let some owner := env.getModuleIdx? companion | throwError "missing proof module {companion}"
  unless env.getModuleIdxFor? proof == some owner do
    throwError "required proof {proof} must be declared in {companion}"
  let some (.thmInfo info) := env.find? proof | throwError "required proof {proof} must be a theorem"
  let sameType ← Lean.Elab.Command.liftTermElabM (Lean.Meta.isDefEq info.type (Lean.mkConst law))
  unless sameType do
    throwError "required proof {proof} must prove the declared law {law}"
  for axiomName in ← Lean.collectAxioms proof do
    unless [` + "\x60propext, \x60Quot.sound, \x60Classical.choice" + `].contains axiomName do
      throwError "required proof {proof} depends on unapproved axiom {axiomName}"
`

func (r renderer) constant(v ir.Constant) string {
	switch v.Type.Kind() {
	case ir.Bool:
		return "_root_.Bool." + v.Value
	case ir.String:
		bytes := make([]string, len(v.Value))
		for i, c := range []byte(v.Value) {
			bytes[i] = strconv.Itoa(int(c))
		}
		return "([" + strings.Join(bytes, ", ") + "] : " + scalar[ir.String] + ")"
	default:
		return "(" + v.Value + " : " + leanType(v.Type) + ")"
	}
}

func (r renderer) expr(e ir.Expr) string {
	switch v := e.Case().(type) {
	case ir.Constant:
		return r.constant(v)
	case ir.Local:
		return local(v.ID)
	case ir.Let:
		return "(let " + local(v.ID) + " := " + r.expr(v.Value) + "; " + r.expr(v.Body) + ")"
	case ir.If:
		if r.measured {
			if neg, ok := v.Cond.Case().(ir.Unary); ok && neg.Op == ir.Not {
				v.Cond, v.Then, v.Else = neg.Value, v.Else, v.Then
			}
			return "(if «_guard» : " + r.expr(v.Cond) + " then " + r.expr(v.Then) + " else " + r.expr(v.Else) + ")"
		}
		return "(if " + r.expr(v.Cond) + " then " + r.expr(v.Then) + " else " + r.expr(v.Else) + ")"
	case ir.Join:
		return "(let " + local(v.ID) + " := fun (_ : _root_.Unit) => " + r.expr(v.Next) + "; " + r.expr(v.Body) + ")"
	case ir.Jump:
		return "(" + local(v.ID) + " ())"
	case ir.Unary:
		return "(!" + r.expr(v.Value) + ")"
	case ir.Binary:
		return r.binary(v)
	case ir.FieldRead:
		return "(" + r.expr(v.Record) + ")." + field(v.Name)
	case ir.FoldStateRead:
		return "(" + r.expr(v.Control) + ").1"
	case ir.FoldStopRead:
		return "(" + r.expr(v.Control) + ").2"
	case ir.StructLiteral:
		return r.applySequence(qualified(v.Type)+".mk", v.Fields)
	case ir.Constructor:
		return r.apply(qualified(v.Enum)+"."+identifier(v.Variant), []ir.Expr{v.Value})
	case ir.Match:
		var b strings.Builder
		b.WriteString("(match ")
		b.WriteString(r.expr(v.Value))
		b.WriteString(" with")
		for next := v.Cases.First; next.IsSome(); {
			item := next.Get()
			c := item.Value
			next = item.Rest.First
			body := r.expr(c.Body)
			binding := "_"
			if c.Binding >= 0 && strings.Contains(body, local(c.Binding)) {
				binding = local(c.Binding)
			}
			fmt.Fprintf(&b, " | .%s %s => %s", identifier(c.Variant), binding, body)
		}
		b.WriteString(")")
		return b.String()
	case ir.Call:
		if r.measured && v.Target == r.self {
			return r.applySequence(identifier(v.Target.Name), v.Args)
		}
		return r.applySequence(qualified(v.Target), v.Args)
	case ir.AbstractCall:
		return r.applySequence(contractVar(v.Target)+".operation", v.Args)
	case ir.PrimitiveExpr:
		return r.primitive(v.Primitive)
	case ir.FoldExpr:
		return r.fold(v.Fold)
	case ir.FoldControlLiteral:
		return r.apply("_root_.Prod.mk", []ir.Expr{v.State, v.Stop})
	default:
		panic(fmt.Sprintf("unexpected IR expression %T", v))
	}
}

func (r renderer) applySequence(fn string, values ir.ExprSeq) string {
	var b strings.Builder
	b.WriteString("(" + fn)
	for next := values.First; next.IsSome(); {
		item := next.Get()
		b.WriteString(" " + r.expr(item.Value))
		next = item.Rest.First
	}
	b.WriteByte(')')
	return b.String()
}

func (r renderer) apply(fn string, values []ir.Expr) string {
	var b strings.Builder
	b.WriteString("(" + fn)
	for _, value := range values {
		b.WriteString(" " + r.expr(value))
	}
	b.WriteByte(')')
	return b.String()
}

func (r renderer) binary(v ir.Binary) string {
	a, b := r.expr(v.Left), r.expr(v.Right)
	if v.Kind == ir.String {
		order := "(_root_.Ord.compare " + a + " " + b + ")"
		switch v.Op {
		case ir.Lt:
			return "(_root_.Decidable.decide (" + order + " = _root_.Ordering.lt))"
		case ir.Le:
			return "(_root_.Decidable.decide (" + order + " ≠ _root_.Ordering.gt))"
		case ir.Gt:
			return "(_root_.Decidable.decide (" + order + " = _root_.Ordering.gt))"
		case ir.Ge:
			return "(_root_.Decidable.decide (" + order + " ≠ _root_.Ordering.lt))"
		}
	}
	switch v.Op {
	case ir.And:
		return "(if " + a + " then " + b + " else _root_.Bool.false)"
	case ir.Or:
		return "(if " + a + " then _root_.Bool.true else " + b + ")"
	case ir.Add:
		return "(" + a + " + " + b + ")"
	case ir.Sub:
		return "(" + a + " - " + b + ")"
	default:
		op := map[ir.BinaryOp]string{ir.Eq: "=", ir.Ne: "≠", ir.Lt: "<", ir.Le: "≤", ir.Gt: ">", ir.Ge: "≥"}[v.Op]
		return "(_root_.Decidable.decide (" + a + " " + op + " " + b + "))"
	}
}

func writeTermination(b *strings.Builder, d ir.Function, hasMutual bool) {
	fmt.Fprint(b, "termination_by (")
	for _, param := range toSlice(d.Params) {
		if !param.Unused {
			fmt.Fprintf(b, "let %s := %s; ", identifier(param.Name), local(param.ID))
		}
	}
	fmt.Fprintf(b, "(%s : _root_.Nat))\n", d.Termination)
	b.WriteString(`decreasing_by
  all_goals simp_wf
  all_goals first
    | solve_by_elim
    | (try simp_all); omega
    | simp_all [UInt8.toNat_sub, UInt16.toNat_sub, UInt32.toNat_sub, UInt64.toNat_sub,
        UInt8.lt_iff_toNat_lt, UInt16.lt_iff_toNat_lt, UInt32.lt_iff_toNat_lt, UInt64.lt_iff_toNat_lt,
        UInt8.le_iff_toNat_le, UInt16.le_iff_toNat_le, UInt32.le_iff_toNat_le, UInt64.le_iff_toNat_le,
        ← UInt8.toNat_inj, ← UInt16.toNat_inj, ← UInt32.toNat_inj, ← UInt64.toNat_inj] <;> omega
`)
	if hasMutual {
		b.WriteString("    | grind\n")
	}
	b.WriteString("    | fail \"go-lean could not prove that the recursive call decreases its termination measure\"\n")
}

func selfBox(t ir.Type, record ir.Symbol) bool {
	box, ok := t.Case().(ir.BoxType)
	return ok && box.Element.Kind() == ir.Record && reference(box.Element) == record
}

func writeStruct(b *strings.Builder, d ir.Struct) {
	name := identifier(d.Symbol.Name)
	if !d.Recursive {
		fmt.Fprintf(b, "\nstructure %s where\n", name)
		for _, f := range toSlice(d.Fields) {
			fmt.Fprintf(b, "  %s : %s\n", field(f.Name), leanType(f.Type))
		}
		return
	}
	writeRecordInductive(b, d, nil)
	writeRecordProjections(b, d, nil)
}

func writeEnum(b *strings.Builder, d ir.Enum, members map[ir.Symbol]bool) {
	fmt.Fprintf(b, "\ninductive %s where\n", identifier(d.Symbol.Name))
	for _, variant := range toSlice(d.Variants) {
		fmt.Fprintf(b, "  | %s (payload : %s)\n", identifier(variant.Name), renderType(variant.Type, members))
	}
}

func writeRecordInductive(b *strings.Builder, d ir.Struct, members map[ir.Symbol]bool) {
	name := identifier(d.Symbol.Name)
	fmt.Fprintf(b, "\ninductive %s where\n  | mk", name)
	for _, f := range toSlice(d.Fields) {
		typ := renderType(f.Type, members)
		if selfBox(f.Type, d.Symbol) {
			typ = "(_root_.Option " + name + ")"
		}
		fmt.Fprintf(b, " (%s : %s)", field(f.Name), typ)
	}
	fmt.Fprintf(b, " : %s\n", name)
}

func writeRecordProjections(b *strings.Builder, d ir.Struct, members map[ir.Symbol]bool) {
	name := identifier(d.Symbol.Name)
	fields := toSlice(d.Fields)
	for i, f := range fields {
		pattern := make([]string, len(fields))
		for j := range pattern {
			pattern[j] = "_"
		}
		pattern[i] = "value"
		projection := field(f.Name)
		fmt.Fprintf(b, "\ndef %s.%s : %s → %s\n  | .mk %s => value\n", name, projection, name, leanType(f.Type), strings.Join(pattern, " "))
		box, isBox := f.Type.Case().(ir.BoxType)
		boxed := isBox && (selfBox(f.Type, d.Symbol) || members[reference(box.Element)])
		direct := members[reference(f.Type)]
		if !boxed && !direct {
			continue
		}
		for j := range pattern {
			pattern[j] = fmt.Sprintf("arg%d", j)
		}
		if boxed {
			binders := "(node fallback : " + name + ")"
			if !selfBox(f.Type, d.Symbol) {
				binders = "(node : " + name + ") (fallback : " + leanType(box.Element) + ")"
			}
			fmt.Fprintf(b, "\n@[local simp] theorem %s.%s %s\n    (present : node.%s.isSome = true) :\n    sizeOf (node.%s.getD fallback) < sizeOf node := by\n", name, identifier("box_size:"+f.Name), binders, projection, projection)
			fmt.Fprintf(b, "  cases node with\n  | mk %s =>\n    cases %s <;> simp_all [%s.%s] <;> omega\n", strings.Join(pattern, " "), pattern[i], name, projection)
			if len(members) > 0 {
				fmt.Fprintf(b, "local grind_pattern %s.%s => node.%s.getD fallback\n", name, identifier("box_size:"+f.Name), projection)
			}
		} else {
			fmt.Fprintf(b, "\ntheorem %s.%s (node : %s) :\n    sizeOf node.%s < sizeOf node := by\n", name, identifier("field_size:"+f.Name), name, projection)
			fmt.Fprintf(b, "  cases node with\n  | mk %s => simp [%s.%s] <;> omega\n", strings.Join(pattern, " "), name, projection)
			fmt.Fprintf(b, "local grind_pattern %s.%s => node.%s\n", name, identifier("field_size:"+f.Name), projection)
		}
	}
	// Only simplify projections on known constructors. Keep a projection on
	// an arbitrary value intact so recursive size lemmas can still match it.
	if len(members) > 0 {
		args := make([]string, len(fields))
		binders := make([]string, len(fields))
		for i, f := range fields {
			args[i] = fmt.Sprintf("arg%d", i)
			binders[i] = fmt.Sprintf("(%s : %s)", args[i], leanType(f.Type))
		}
		for i, f := range fields {
			fmt.Fprintf(b, "\n@[simp] theorem %s.%s %s :\n    (%s.mk %s).%s = %s := rfl\n",
				name, identifier("field_mk:"+f.Name), strings.Join(binders, " "),
				name, strings.Join(args, " "), field(f.Name), args[i])
		}
	}
}
