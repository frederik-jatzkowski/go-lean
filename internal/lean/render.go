// Package lean renders a validated Go Lean IR program as Lean 4 source.
package lean

import (
	"fmt"
	"maps"
	"slices"
	"strconv"
	"strings"

	"github.com/frederik-jatzkowski/go-lean/internal/ir"
)

const GeneratedHeader = "-- Code generated by go-lean. DO NOT EDIT."

type renderer struct {
	tracedRoots map[ir.Symbol]bool
	wordBits    int64
	records     map[ir.Type]ir.Record
	contracts   map[ir.Type]ir.Contract
	abstract    map[ir.Symbol]string
}

func Render(program ir.Program) string {
	return RenderVerification(program, Verification{})
}

func RenderVerification(program ir.Program, verification Verification) string {
	var out strings.Builder
	r := renderer{wordBits: program.WordBits, records: program.Records, contracts: program.Contracts, tracedRoots: program.TracedRoots}
	out.WriteString(GeneratedHeader + "\nimport Init\n")
	for _, module := range verification.ModelImports {
		fmt.Fprintf(&out, "import %s\n", module)
	}
	if len(verification.Roots) != 0 || len(verification.Constructors) != 0 {
		out.WriteString("import Lean.Elab.Command\n")
	}
	// Go allows unused parameters, and they are part of the generated signature.
	out.WriteString("\nset_option linter.unusedVariables false\n")
	out.WriteString("\nnamespace GoLean\n")
	if program.WordBits != 0 {
		scope := symbolScope(verification.Scope)
		if verification.Scope.Package == "" {
			scope = symbolScope(program.Functions[0].Symbol)
		}
		fmt.Fprintf(&out, "\nabbrev %s.GoTypes.Int := %s\n", scope, r.leanType(ir.IntWord))
		fmt.Fprintf(&out, "abbrev %s.GoTypes.UInt := %s\n", scope, r.leanType(ir.UIntWord))
		fmt.Fprintf(&out, "abbrev %s.GoTypes.WordBits : Nat := %d\n", scope, program.WordBits)
	}
	r.renderRecords(&out, verification.PackagePath)
	r.renderContracts(&out, verification.PackagePath)
	if len(verification.Roots) != 0 {
		out.WriteString(declareLaw)
		for _, root := range verification.Roots {
			for _, target := range root.Abstract {
				r.renderAbstractContract(&out, root, target)
			}
		}
	}
	for _, fn := range program.Functions {
		root := verification.root(fn.Symbol)
		r.abstract = make(map[ir.Symbol]string, len(root.Abstract))
		for _, target := range root.Abstract {
			r.abstract[target.Call] = abstractBinder(target) + ".operation"
		}
		if fn.Loop != nil {
			r.renderCountedLoop(&out, *fn.Loop)
		}
		name := symbolName(fn.Symbol)
		if !fn.Traced {
			name = r.untracedName(fn.Symbol)
		}
		recursion, recursive := fn.Body.Result.(ir.ListRecursion)
		if recursive || fn.Fuel != nil {
			fmt.Fprintf(&out, "\nnamespace %s\n", symbolNamespace(fn.Symbol))
			name = quoted(fn.Symbol.Name)
		}
		fmt.Fprintf(&out, "\ndef %s", name)
		for _, param := range fn.TypeParams {
			fmt.Fprintf(&out, " {%s : Type}", param)
		}
		for _, handle := range fn.Contracts {
			fmt.Fprintf(&out, " {%s : Type}", r.leanType(handle))
			if !verification.Constructors[fn.Symbol] {
				fmt.Fprintf(&out, " (%s : %s %s)", contractBinder(handle), contractName(r.contracts[handle]), r.leanType(handle))
			}
		}
		for _, target := range root.Abstract {
			fmt.Fprintf(&out, " (%s : %s)", abstractBinder(target), abstractType(root, target))
		}
		r.renderParams(&out, fn.Params)
		if fn.CanPanic {
			fmt.Fprintf(&out, " : Option %s := do\n", r.leanType(fn.Result))
		} else {
			fmt.Fprintf(&out, " : %s :=\n", r.leanType(fn.Result))
		}
		if fn.Fuel != nil {
			fuel := binderName(*fn.Fuel)
			fmt.Fprintf(&out, "  match %s with\n  | 0 => none\n  | %s + 1 => do\n", fuel, fuel)
			r.renderBody(&out, fn.Body, "    ", true)
			fmt.Fprintf(&out, "termination_by structural %s\n", fuel)
		} else {
			r.renderBody(&out, fn.Body, "  ", fn.CanPanic)
		}
		if recursive {
			fmt.Fprintf(&out, "termination_by structural %s\n", binderName(recursion.Input))
		}
		if recursive || fn.Fuel != nil {
			fmt.Fprintf(&out, "\nend %s\n", symbolNamespace(fn.Symbol))
		}
		if verification.Constructors[fn.Symbol] {
			r.renderConstructorProof(&out, fn)
		}
	}
	if !verification.SeparateLaws {
		for _, root := range verification.Roots {
			renderLaws(&out, root, verification.Scope)
		}
	}
	out.WriteString("\nend GoLean\n")
	return out.String()
}

func (r renderer) renderParams(out *strings.Builder, params []ir.Binder) {
	for _, param := range params {
		fmt.Fprintf(out, " (%s : %s)", binderName(param), r.leanType(param.Type))
	}
}

func (r renderer) renderConstructorProof(out *strings.Builder, fn ir.Function) {
	name := symbolName(fn.Symbol)
	theorem := fn.Symbol
	theorem.Name += "$initialized"
	fmt.Fprintf(out, "\n/-- Initialized inputs give initialized interface fields in the returned value. -/\ntheorem %s", symbolName(theorem))
	for _, handle := range fn.Contracts {
		fmt.Fprintf(out, " {%s : Type}", r.leanType(handle))
	}
	args := []string{name}
	var hypotheses []string
	for _, param := range fn.Params {
		typ := param.Type
		if _, isInterface := r.contracts[typ]; isInterface {
			typ = ir.OptionType(typ)
			hypotheses = append(hypotheses, binderName(param))
		}
		fmt.Fprintf(out, " (%s : %s)", binderName(param), r.leanType(typ))
		args = append(args, binderName(param))
	}
	for i, hypothesis := range hypotheses {
		fmt.Fprintf(out, " (initialized%d : %s.isSome = true)", i, hypothesis)
	}
	var fields []string
	for _, field := range r.records[fn.Result].Fields {
		if _, isInterface := r.contracts[field.Type]; isInterface {
			fields = append(fields, fmt.Sprintf("(%s).%s.isSome = true", strings.Join(args, " "), recordFieldName(field.Name)))
		}
	}
	fmt.Fprintf(out, " :\n  %s := by\n  simp only [%s]\n  repeat' split\n  all_goals simp_all\n", strings.Join(fields, " ∧\n  "), name)
}

func (r renderer) renderCountedLoop(out *strings.Builder, loop ir.CountedLoop) {
	ns, name := symbolNamespace(loop.Symbol), quoted(loop.Symbol.Name)
	state, typ := binderName(loop.State), r.leanType(loop.State.Type)
	fmt.Fprintf(out, "\nnamespace %s\n\ndef %s", ns, name)
	r.renderParams(out, loop.Params)
	if loop.CanPanic {
		fmt.Fprintf(out, " : Nat → %s → Option (%s)\n", typ, typ)
		fmt.Fprintf(out, "  | 0, %s => some %s\n", state, state)
		fmt.Fprintf(out, "  | fuel + 1, %s => do\n", state)
		fmt.Fprintln(out, "    let nextState ← (do")
		r.renderBody(out, *loop.Body, "      ", true)
		fmt.Fprintln(out, "    )")
	} else {
		fmt.Fprintf(out, " : Nat → %s → %s\n", typ, typ)
		fmt.Fprintf(out, "  | 0, %s => %s\n", state, state)
		fmt.Fprintf(out, "  | fuel + 1, %s =>\n", state)
		if loop.Body != nil {
			fmt.Fprintln(out, "    let nextState :=")
			r.renderBody(out, *loop.Body, "      ", false)
		} else {
			r.renderBindings(out, loop.Steps, "    ")
		}
	}
	fmt.Fprintf(out, "    %s", name)
	for _, param := range loop.Params {
		fmt.Fprintf(out, " %s", binderName(param))
	}
	if loop.Body != nil {
		fmt.Fprintln(out, " fuel nextState")
	} else {
		fmt.Fprintf(out, " fuel %s\n", r.renderExpr(loop.Next))
	}
	fmt.Fprintf(out, "\nend %s\n", ns)
}

func (r renderer) renderRecords(out *strings.Builder, owner string) {
	emitted := make(map[ir.Type]bool)
	var emit func(ir.Type)
	emit = func(typ ir.Type) {
		record, exists := r.records[typ]
		if !exists || emitted[typ] || (owner != "" && record.Symbol.Package != owner) {
			return
		}
		emitted[typ] = true
		for _, field := range record.Fields {
			typ := field.Type
			if elem := typ.OptionElem(); elem != "" {
				typ = elem
			}
			if elem := typ.SliceElem(); elem != "" {
				typ = elem
			}
			if elem := typ.BufferElem(); elem != "" {
				typ = elem
			}
			if elem, _ := typ.ArrayShape(); elem != "" {
				typ = elem
			}
			emit(typ)
		}
		fmt.Fprintf(out, "\nstructure %s", symbolName(record.Symbol))
		for _, handle := range record.Handles {
			fmt.Fprintf(out, " (%s : Type)", r.leanType(handle))
		}
		out.WriteString(" where\n")
		for _, field := range record.Fields {
			fmt.Fprintf(out, "  %s : %s\n", recordFieldName(field.Name), r.leanType(field.Type))
		}
	}
	for _, typ := range slices.Sorted(maps.Keys(r.records)) {
		emit(typ)
	}
}

func contractName(contract ir.Contract) string {
	return "_root_.GoLean." + contractDeclaration(contract)
}

func contractDeclaration(contract ir.Contract) string {
	return symbolNamespace(contract.Symbol) + ".InterfaceContracts." + quoted(contract.Symbol.Name)
}

func contractBinder(handle ir.Type) string {
	return quoted("contract:" + string(handle))
}

func (r renderer) renderContracts(out *strings.Builder, owner string) {
	for _, handle := range slices.Sorted(maps.Keys(r.contracts)) {
		contract := r.contracts[handle]
		if owner != "" && contract.Symbol.Package != owner {
			continue
		}
		fmt.Fprintf(out, "\nstructure %s (%s : Type) where\n", contractDeclaration(contract), r.leanType(handle))
		for _, method := range contract.Methods {
			fmt.Fprintf(out, "  %s : %s", quoted(method.Name), r.leanType(handle))
			for _, param := range method.Params {
				fmt.Fprintf(out, " → %s", r.leanType(param))
			}
			fmt.Fprintf(out, " → %s\n", r.leanType(method.Result))
		}
		for _, line := range contract.Laws {
			if line == "" {
				out.WriteByte('\n')
			} else {
				fmt.Fprintf(out, "  %s\n", line)
			}
		}
	}
}

func (r renderer) leanType(typ ir.Type) string {
	if left, right := typ.ProductShape(); left != "" {
		return "(" + r.leanType(left) + " × " + r.leanType(right) + ")"
	}
	if input, output := typ.UnaryFunctionShape(); input != "" {
		return "(" + r.leanType(input) + " → " + r.leanType(output) + ")"
	}
	if elem := typ.SliceElem(); elem != "" {
		return "(List " + r.leanType(elem) + ")"
	}
	if elem := typ.BufferElem(); elem != "" {
		return "(Array " + r.leanType(elem) + ")"
	}
	if elem, length := typ.ArrayShape(); elem != "" {
		return "(Vector " + r.leanType(elem) + " " + length + ")"
	}
	if key, value := typ.MapShape(); key != "" {
		return "(List (" + r.leanType(key) + " × " + r.leanType(value) + "))"
	}
	if elem := typ.OptionElem(); elem != "" {
		return "(Option " + r.leanType(elem) + ")"
	}
	if pointee := typ.Pointee(); pointee != "" {
		return "(Option " + r.leanType(pointee) + ")"
	}
	if _, ok := r.contracts[typ]; ok {
		return quoted("handle:" + string(typ))
	}
	if record, ok := r.records[typ]; ok {
		name := "_root_.GoLean." + symbolName(record.Symbol)
		if len(record.Handles) == 0 {
			return name
		}
		args := []string{name}
		for _, handle := range record.Handles {
			args = append(args, r.leanType(handle))
		}
		return "(" + strings.Join(args, " ") + ")"
	}
	switch typ {
	case ir.IntWord:
		return fmt.Sprintf("Int%d", r.wordBits)
	case ir.UIntWord:
		return fmt.Sprintf("UInt%d", r.wordBits)
	default:
		return string(typ)
	}
}

func (r renderer) renderBody(out *strings.Builder, body ir.Body, indent string, canPanic bool) {
	r.renderBindings(out, body.Bindings, indent)
	switch result := body.Result.(type) {
	case ir.Return:
		out.WriteString(indent)
		if canPanic {
			out.WriteString("return ")
		}
		fmt.Fprintln(out, r.renderExpr(result.Value))
	case ir.TailCall:
		if result.Recursive {
			fmt.Fprint(out, indent+quoted(result.Call.Callee.Name))
			for _, arg := range result.Call.Args {
				fmt.Fprint(out, " "+r.renderExpr(arg))
			}
			fmt.Fprintln(out)
		} else {
			fmt.Fprintln(out, indent+r.renderExpr(result.Call))
		}
	case ir.WithReceiver:
		fmt.Fprintf(out, "%smatch %s with\n%s| none => none\n%s| some %s =>\n",
			indent, r.renderExpr(result.Receiver), indent, indent, binderName(result.State))
		r.renderBody(out, result.Body, indent+"  ", canPanic)
	case ir.If:
		fmt.Fprintf(out, "%sif %s then\n", indent, r.renderExpr(result.Condition))
		r.renderBody(out, result.Then, indent+"  ", canPanic)
		fmt.Fprintf(out, "%selse\n", indent)
		r.renderBody(out, result.Else, indent+"  ", canPanic)
	case ir.ListFold:
		fmt.Fprintf(out, "%sList.foldl (fun", indent)
		r.renderParams(out, []ir.Binder{result.State, result.Element})
		out.WriteString(" =>\n")
		r.renderBindings(out, result.Steps, indent+"  ")
		fmt.Fprintf(out, "%s%s) %s %s\n",
			indent+"  ", r.renderExpr(result.Next), r.renderExpr(result.Initial), r.renderExpr(result.Sequence))
	case ir.StructuredFold:
		operator, fold := ":=", "List.foldl"
		if result.Effectful {
			operator, fold = "←", "List.foldlM"
		}
		fmt.Fprintf(out, "%slet %s %s %s (fun", indent, binderName(result.Final), operator, fold)
		r.renderParams(out, []ir.Binder{result.State, result.Element})
		out.WriteString(" =>")
		if result.Effectful {
			out.WriteString(" do")
		}
		out.WriteString("\n")
		r.renderBody(out, result.Iteration, indent+"  ", result.Effectful)
		fmt.Fprintf(out, "%s) %s %s\n", indent, r.renderExpr(result.Initial), r.renderExpr(result.Sequence))
		r.renderBody(out, result.Continuation, indent, canPanic)
	case ir.BoundedControl:
		name := binderName(result.Function)
		state, stateType := binderName(result.State), r.leanType(result.State.Type)
		resultType := r.leanType(result.Result)
		do := ""
		if result.CanPanic {
			resultType = "Option (" + resultType + ")"
			do = " do"
		}
		fmt.Fprintf(out, "%slet rec %s : Nat → %s → %s\n", indent, name, stateType, resultType)
		fmt.Fprintf(out, "%s  | 0, %s =>%s\n", indent, state, do)
		r.renderBody(out, result.Done, indent+"    ", result.CanPanic)
		fmt.Fprintf(out, "%s  | fuel + 1, %s =>%s\n", indent, state, do)
		r.renderBody(out, result.Step, indent+"    ", result.CanPanic)
		fmt.Fprint(out, indent)
		if canPanic && !result.CanPanic {
			fmt.Fprint(out, "return ")
		}
		fmt.Fprintf(out, "%s %s %s\n", name, r.renderExpr(result.Fuel), r.renderExpr(result.Initial))
	case ir.AdvanceLoop:
		fmt.Fprintf(out, "%s%s fuel %s\n", indent, binderName(result.Function), r.renderExpr(result.State))
	case ir.ListBuild:
		if result.Destination != nil {
			operator, traversal := ":=", "List.map"
			if result.Effectful {
				operator, traversal = "←", "List.mapM"
			}
			fmt.Fprintf(out, "%slet %s : %s %s %s (fun", indent, binderName(*result.Destination), r.leanType(result.Destination.Type), operator, traversal)
		} else if result.Effectful {
			fmt.Fprintf(out, "%sList.mapM (fun", indent)
		} else {
			fmt.Fprintf(out, "%sreturn List.map (fun", indent)
		}
		r.renderParams(out, []ir.Binder{result.Element})
		if result.Body != nil {
			out.WriteString(" =>")
			if result.Effectful {
				out.WriteString(" do")
			}
			out.WriteString("\n")
			r.renderBody(out, *result.Body, indent+"  ", result.Effectful)
			fmt.Fprintf(out, "%s) %s\n", indent, r.renderExpr(result.Sequence))
		} else {
			out.WriteString(" =>\n")
			r.renderBindings(out, result.Steps, indent+"  ")
			fmt.Fprintf(out, "%s%s) %s\n", indent+"  ", r.renderExpr(result.Next), r.renderExpr(result.Sequence))
		}
		if result.Continuation != nil {
			r.renderBody(out, *result.Continuation, indent, canPanic)
		}
	case ir.ListRecursion:
		head := "_"
		if result.Head != nil {
			head = binderName(*result.Head)
		}
		fmt.Fprintf(out, "%smatch %s with\n", indent, binderName(result.Input))
		fmt.Fprintf(out, "%s| [] => %s\n", indent, r.renderExpr(result.Base))
		fmt.Fprintf(out, "%s| %s :: %s =>\n", indent, head, binderName(result.Tail))
		r.renderBody(out, result.Step, indent+"  ", false)
	default:
		panic("unexpected IR result")
	}
}

func (r renderer) renderBindings(out *strings.Builder, bindings []ir.Binding, indent string) {
	for _, binding := range bindings {
		operator := ":="
		if binding.CanPanic {
			operator = "←"
		}
		fmt.Fprintf(out, "%slet %s : %s %s %s\n", indent, binderName(binding.Binder), r.leanType(binding.Binder.Type), operator, r.renderExpr(binding.Value))
	}
}

func (r renderer) renderExpr(expr ir.Expr) string {
	switch expr := expr.(type) {
	case ir.Trace:
		if expr == "" {
			return "[]"
		}
		return "[" + strconv.Quote(string(expr)) + "]"
	case ir.TraceAppend:
		return fmt.Sprintf("(%s ++ %s)", r.renderExpr(expr.Before), r.renderExpr(expr.After))
	case ir.UnitLiteral:
		return "()"
	case ir.Some:
		return "(some " + r.renderExpr(expr.Value) + ")"
	case ir.Pair:
		return fmt.Sprintf("(%s, %s)", r.renderExpr(expr.Left), r.renderExpr(expr.Right))
	case ir.PairField:
		field := 1
		if expr.Second {
			field = 2
		}
		return fmt.Sprintf("(%s).%d", r.renderExpr(expr.Value), field)
	case ir.RecordUpdate:
		return fmt.Sprintf("{ %s with %s := %s }", r.renderExpr(expr.Record), recordFieldName(expr.Field), r.renderExpr(expr.Value))
	case ir.ListLength:
		return fmt.Sprintf("(%s).length", r.renderExpr(expr.List))
	case ir.SliceLength:
		return fmt.Sprintf("(%s.ofNat (%s).length)", r.leanType(ir.IntWord), r.renderExpr(expr.List))
	case ir.Cons:
		return fmt.Sprintf("(%s :: %s)", r.renderExpr(expr.Head), r.renderExpr(expr.Tail))
	case ir.Reverse:
		return fmt.Sprintf("(%s).reverse", r.renderExpr(expr.List))
	case ir.IndexFuel:
		return fmt.Sprintf("(((%s).toInt - (%s).toInt).toNat + 1)", r.renderExpr(expr.Length), r.renderExpr(expr.Cursor))
	case ir.IntLiteral:
		if expr.Type.IsUnsigned() {
			return fmt.Sprintf("(%s.ofNat (%s))", r.leanType(expr.Type), expr.Value)
		}
		return fmt.Sprintf("(%s.ofInt (%s))", r.leanType(expr.Type), expr.Value)
	case ir.BoolLiteral:
		if expr {
			return "true"
		}
		return "false"
	case ir.CollectionFold:
		sequence, excluded := r.renderExpr(expr.Sequence), r.renderExpr(expr.Excluded)
		word := r.leanType(ir.IntWord)
		return fmt.Sprintf(`(let keys := %s
   let result := keys.foldl (fun (acc : List ByteArray × List (ByteArray × %s)) key =>
     if key == %s then acc else
       let count := (List.lookup key acc.2).getD 0 + 1
       (key :: acc.1, (key, count) :: acc.2.filter (fun entry => !(key == entry.1)))) ([], [])
   (some (result.1.reverse, keys.length), result.2))`, sequence, word, excluded)
	case ir.NatZero:
		return "0"
	case ir.SliceAppend:
		if expr.WithoutCapacity {
			slice, element := r.renderExpr(expr.Slice), r.renderExpr(expr.Element)
			if expr.Nullable {
				return fmt.Sprintf("(Option.map (fun s => s ++ [%s]) %s)", element, slice)
			}
			return fmt.Sprintf("(%s ++ [%s])", slice, element)
		}
		return fmt.Sprintf("(Option.map (fun slice => (slice.1 ++ [%s], slice.2)) %s)",
			r.renderExpr(expr.Element), r.renderExpr(expr.Slice))
	case ir.MakeSlice:
		length := r.integerAsInt(expr.Length, expr.LengthType)
		capacity := r.integerAsInt(expr.Capacity, expr.CapacityType)
		value := "(List.replicate length.toNat " + r.renderExpr(expr.Zero) + ")"
		if expr.Array {
			value = "(Array.replicate length.toNat " + r.renderExpr(expr.Zero) + ")"
		}
		if expr.TracksCapacity {
			value = "(some (" + value + ", capacity.toNat))"
		} else if expr.Nullable {
			value = "(some " + value + ")"
		}
		maxInt := uint64(1)<<(r.wordBits-1) - 1
		return fmt.Sprintf("(let length := %s; let capacity := %s; if 0 ≤ length ∧ length ≤ capacity ∧ capacity ≤ %d then some %s else none)", length, capacity, maxInt, value)
	case ir.SliceSet:
		sequence, index, value := r.renderExpr(expr.Slice), r.indexNat(expr.Index, expr.IndexType), r.renderExpr(expr.Value)
		if expr.TracksCapacity {
			return fmt.Sprintf("(Option.map (fun s => (s.1.set %s %s, s.2)) %s)", index, value, sequence)
		}
		if expr.Nullable {
			return fmt.Sprintf("(Option.map (fun s => s.set %s %s) %s)", index, value, sequence)
		}
		return fmt.Sprintf("((%s).set %s %s)", sequence, index, value)
	case ir.SliceCapacity:
		return fmt.Sprintf("(%s.ofNat ((%s).getD ([], 0)).2)", r.leanType(ir.IntWord), r.renderExpr(expr.Slice))
	case ir.EmptyBuffer:
		return "#[]"
	case ir.BufferLength:
		return fmt.Sprintf("(%s.ofNat ((%s).getD #[]).size)", r.leanType(ir.IntWord), r.renderExpr(expr.Buffer))
	case ir.BufferAppend:
		return fmt.Sprintf("(some (((%s).getD #[]).push %s))", r.renderExpr(expr.Buffer), r.renderExpr(expr.Element))
	case ir.BufferSet:
		return fmt.Sprintf("(some (((%s).getD #[]).setIfInBounds %s %s))",
			r.renderExpr(expr.Buffer), r.indexNat(expr.Index, expr.IndexType), r.renderExpr(expr.Value))
	case ir.StringLiteral:
		return strconv.Quote(string(expr))
	case ir.CheckedStringSlice:
		bytes := r.renderExpr(expr.Bytes)
		low, high := "(0 : Int)", fmt.Sprintf("(Int.ofNat (%s).size)", bytes)
		if expr.Low != nil {
			low = r.integerAsInt(expr.Low, expr.LowType)
		}
		if expr.High != nil {
			high = r.integerAsInt(expr.High, expr.HighType)
		}
		return fmt.Sprintf("(let low := %s; let high := %s; if 0 ≤ low ∧ low ≤ high ∧ high ≤ Int.ofNat (%s).size then some ((%s).extract low.toNat high.toNat) else none)",
			low, high, bytes, bytes)
	case ir.BytesLiteral:
		bytes := make([]string, len(expr))
		for i := range bytes {
			bytes[i] = fmt.Sprintf("%d", expr[i])
		}
		return "(ByteArray.mk #[" + strings.Join(bytes, ", ") + "])"
	case ir.BytesToList:
		return fmt.Sprintf("(%s).data.toList", r.renderExpr(expr.Value))
	case ir.Float32Literal:
		return fmt.Sprintf("(Float32.ofBits 0x%08x)", uint32(expr))
	case ir.Float64Literal:
		return fmt.Sprintf("(Float.ofBits 0x%016x)", uint64(expr))
	case ir.ByteLen:
		return fmt.Sprintf("(%s.ofNat (%s).size)", r.leanType(ir.IntWord), r.renderExpr(expr.Value))
	case ir.LoopFuel:
		bound := r.renderExpr(expr.Bound)
		if expr.ZeroStart {
			if expr.Signed {
				return fmt.Sprintf("((%s).toInt.toNat)", bound)
			}
			return fmt.Sprintf("(%s).toNat", bound)
		}
		start := r.renderExpr(expr.Start)
		if expr.Signed {
			return fmt.Sprintf("(((%s).toInt - (%s).toInt).toNat)", bound, start)
		}
		return fmt.Sprintf("((%s).toNat - (%s).toNat)", bound, start)
	case ir.RecordLiteral:
		args := []string{"_root_.GoLean." + symbolName(r.records[expr.Type].Symbol) + ".mk"}
		for _, field := range expr.Values {
			args = append(args, r.renderExpr(field))
		}
		return "(" + strings.Join(args, " ") + ")"
	case ir.RecordField:
		return fmt.Sprintf("(%s).%s", r.renderExpr(expr.Value), recordFieldName(expr.Name))
	case ir.CheckedRecordField:
		return fmt.Sprintf("(Option.map (fun (record : %s) => record.%s) %s)",
			r.leanType(expr.Type), recordFieldName(expr.Name), r.renderExpr(expr.Value))
	case ir.NilPointer:
		return "none"
	case ir.EmptySlice, ir.EmptyMap:
		return "[]"
	case ir.MapLookup:
		return fmt.Sprintf("(List.lookup %s %s)", r.renderExpr(expr.Key), r.renderExpr(expr.Map))
	case ir.MapUpdate:
		key := r.renderExpr(expr.Key)
		return fmt.Sprintf("((%s, %s) :: (%s).filter (fun entry => !(%s == entry.1)))",
			key, r.renderExpr(expr.Value), r.renderExpr(expr.Map), key)
	case ir.OptionGetD:
		return fmt.Sprintf("(Option.getD %s %s)", r.renderExpr(expr.Value), r.renderExpr(expr.Default))
	case ir.OptionIsSome:
		return fmt.Sprintf("(Option.isSome %s)", r.renderExpr(expr.Value))
	case ir.CheckedIndex:
		sequence, index := r.renderExpr(expr.Sequence), r.renderExpr(expr.Index)
		if elem, _ := expr.SequenceType.ArrayShape(); elem != "" {
			sequence = "(" + sequence + ").toArray"
		}
		if expr.IndexType.IsUnsigned() {
			return fmt.Sprintf("(%s)[(%s).toNat]?", sequence, index)
		}
		return fmt.Sprintf("if (%s).toInt < 0 then none else (%s)[(%s).toInt.toNat]?", index, sequence, index)
	case ir.ArrayReplicate:
		return fmt.Sprintf("(Vector.replicate %s %s)", expr.Length, r.renderExpr(expr.Value))
	case ir.ArrayGet:
		return fmt.Sprintf("(Vector.getD %s %s %s)", r.renderExpr(expr.Sequence), r.indexNat(expr.Index, expr.IndexType), r.renderExpr(expr.Default))
	case ir.ArraySet:
		return fmt.Sprintf("(Vector.setIfInBounds %s %s %s)", r.renderExpr(expr.Sequence), r.indexNat(expr.Index, expr.IndexType), r.renderExpr(expr.Value))
	case ir.Ref:
		return binderName(ir.Binder(expr))
	case ir.Negate:
		return "(-" + r.renderExpr(expr.Value) + ")"
	case ir.Not:
		return "(!" + r.renderExpr(expr.Value) + ")"
	case ir.Convert:
		value := r.renderExpr(expr.Value)
		target := r.leanType(expr.To)
		if expr.From.IsWord() && expr.To.IsWord() {
			return fmt.Sprintf("(%s).to%s", value, target)
		}
		if expr.From.IsUnsigned() {
			if expr.To.IsUnsigned() {
				return fmt.Sprintf("(%s.ofNat (%s).toNat)", target, value)
			}
			return fmt.Sprintf("(%s.ofInt (Int.ofNat (%s).toNat))", target, value)
		}
		if expr.To.IsUnsigned() {
			signed := strings.TrimPrefix(target, "U")
			return fmt.Sprintf("(%s.ofInt (%s).toInt).to%s", signed, value, target)
		}
		return fmt.Sprintf("(%s.ofInt (%s).toInt)", target, value)
	case ir.IntegerExtremum:
		value := r.renderExpr(expr.Args[0])
		operator := "<"
		if expr.Max {
			operator = ">"
		}
		for _, arg := range expr.Args[1:] {
			next := r.renderExpr(arg)
			value = fmt.Sprintf("(let best := %s; if %s %s best then %s else best)", value, next, operator, next)
		}
		return value
	case ir.Binary:
		left, right := r.renderExpr(expr.Left), r.renderExpr(expr.Right)
		if expr.OperandType == ir.Bytes {
			switch expr.Op {
			case ir.Equal:
				return fmt.Sprintf("((%s).data == (%s).data)", left, right)
			case ir.NotEqual:
				return fmt.Sprintf("(!((%s).data == (%s).data))", left, right)
			default:
				return fmt.Sprintf("(%s ++ %s)", left, right)
			}
		}
		if expr.OperandType == ir.Float64 {
			return renderFloatComparison(expr.Op, left, right)
		}
		if expr.Op == ir.Divide {
			if expr.OperandType.IsUnsigned() {
				return fmt.Sprintf("if %s = 0 then none else some (%s / %s)", right, left, right)
			}
			return fmt.Sprintf("if %s = 0 then none else some (%s.ofInt ((%s).toInt.tdiv (%s).toInt))", right, r.leanType(expr.OperandType), left, right)
		}
		if expr.Op == ir.Remainder {
			return fmt.Sprintf("if %s = 0 then none else some (%s %% %s)", right, left, right)
		}
		value := fmt.Sprintf("(%s %s %s)", left, operators[expr.Op], right)
		if expr.Op >= ir.Equal {
			return "(decide " + value + ")"
		}
		return value
	case ir.Call:
		call := "_root_.GoLean." + r.untracedName(expr.Callee)
		if abstract, ok := r.abstract[expr.Callee]; ok {
			call = abstract
		}
		if len(expr.Args) == 0 && len(expr.Contracts) == 0 {
			return call
		}
		args := []string{call}
		for _, handle := range expr.Contracts {
			args = append(args, contractBinder(handle))
		}
		for _, arg := range expr.Args {
			args = append(args, r.renderExpr(arg))
		}
		return "(" + strings.Join(args, " ") + ")"
	case ir.InterfaceCall:
		args := []string{contractBinder(expr.Contract) + "." + quoted(expr.Method)}
		for _, arg := range expr.Args {
			args = append(args, r.renderExpr(arg))
		}
		return "(" + strings.Join(args, " ") + ")"
	case ir.LiftCallback:
		return "(fun value => some (" + r.renderExpr(expr.Function) + " value))"
	case ir.FunctionRef:
		return "_root_.GoLean." + r.untracedName(ir.Symbol(expr))
	case ir.Apply:
		return "(" + r.renderExpr(expr.Function) + " " + r.renderExpr(expr.Argument) + ")"
	case ir.SelfCall:
		args := []string{quoted(expr.Name)}
		for _, arg := range expr.Args {
			args = append(args, r.renderExpr(arg))
		}
		return "(" + strings.Join(args, " ") + ")"
	default:
		panic("unexpected IR expression")
	}
}

func (r renderer) integerAsInt(value ir.Expr, typ ir.Type) string {
	rendered := r.renderExpr(value)
	if typ.IsUnsigned() {
		return fmt.Sprintf("(Int.ofNat (%s).toNat)", rendered)
	}
	return fmt.Sprintf("(%s).toInt", rendered)
}

func (r *renderer) indexNat(index ir.Expr, typ ir.Type) string {
	if typ.IsUnsigned() {
		return fmt.Sprintf("(%s).toNat", r.renderExpr(index))
	}
	return fmt.Sprintf("(%s).toInt.toNat", r.renderExpr(index))
}

func renderFloatComparison(op ir.Operator, left, right string) string {
	switch op {
	case ir.Equal:
		return fmt.Sprintf("(%s == %s)", left, right)
	case ir.NotEqual:
		return fmt.Sprintf("(!(%s == %s))", left, right)
	case ir.Less:
		return fmt.Sprintf("(Float.lt %s %s)", left, right)
	case ir.LessEqual:
		return fmt.Sprintf("(Float.le %s %s)", left, right)
	case ir.Greater:
		return fmt.Sprintf("(Float.lt %s %s)", right, left)
	case ir.GreaterEqual:
		return fmt.Sprintf("(Float.le %s %s)", right, left)
	default:
		panic("unexpected float64 comparison")
	}
}

var operators = [...]string{
	ir.Add:          "+",
	ir.Subtract:     "-",
	ir.Multiply:     "*",
	ir.Equal:        "=",
	ir.NotEqual:     "≠",
	ir.Less:         "<",
	ir.LessEqual:    "≤",
	ir.Greater:      ">",
	ir.GreaterEqual: "≥",
}

func quoted(name string) string { return "«" + name + "»" }

func recordFieldName(name string) string { return quoted("field:" + name) }

func symbolScope(symbol ir.Symbol) string {
	if symbol.File == "" {
		return quoted(symbol.Package)
	}
	return quoted(symbol.Package) + "." + quoted(symbol.File)
}

func symbolNamespace(symbol ir.Symbol) string {
	name := symbolScope(symbol)
	if symbol.Dependency != "" {
		name += ".Dependencies." + quoted(symbol.Dependency)
	}
	return name
}

func symbolName(symbol ir.Symbol) string {
	return symbolNamespace(symbol) + "." + quoted(symbol.Name)
}

func (r renderer) untracedName(symbol ir.Symbol) string {
	if r.tracedRoots[symbol] {
		symbol.Name += "$untraced"
	}
	return symbolName(symbol)
}

func binderName(binder ir.Binder) string {
	return quoted(fmt.Sprintf("v%d_%s", binder.Index, binder.Name))
}
