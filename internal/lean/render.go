// Package lean renders a validated Go Lean IR program as Lean 4 source.
package lean

import (
	"fmt"
	"strings"

	"github.com/frederik-jatzkowski/go-lean/internal/ir"
)

const GeneratedHeader = "-- Code generated by go-lean. DO NOT EDIT."

func Render(program ir.Program) string {
	var out strings.Builder
	out.WriteString(GeneratedHeader + "\nimport Init\n")
	// Go allows unused parameters, and they are part of the generated signature.
	out.WriteString("\nset_option linter.unusedVariables false\n")
	out.WriteString("\nnamespace GoLean\n")
	for _, fn := range program.Functions {
		fmt.Fprintf(&out, "\ndef %s", symbolName(fn.Symbol))
		for _, param := range fn.Params {
			fmt.Fprintf(&out, " (%s : Int64)", binderName(param))
		}
		out.WriteString(" : Int64 :=\n")
		renderBody(&out, fn.Body, "  ")
	}
	out.WriteString("\nend GoLean\n")
	return out.String()
}

func renderBody(out *strings.Builder, body ir.Body, indent string) {
	for _, binding := range body.Bindings {
		fmt.Fprintf(out, "%slet %s : Int64 := %s\n", indent, binderName(binding.Binder), renderExpr(binding.Value))
	}
	switch result := body.Result.(type) {
	case ir.Return:
		fmt.Fprintf(out, "%s%s\n", indent, renderExpr(result.Value))
	case ir.If:
		fmt.Fprintf(out, "%sif %s then\n", indent, renderExpr(result.Condition))
		renderBody(out, result.Then, indent+"  ")
		fmt.Fprintf(out, "%selse\n", indent)
		renderBody(out, result.Else, indent+"  ")
	default:
		panic("unexpected IR result")
	}
}

func renderExpr(expr ir.Expr) string {
	switch expr := expr.(type) {
	case ir.IntLiteral:
		return fmt.Sprintf("(Int64.ofInt (%s))", expr)
	case ir.BoolLiteral:
		if expr {
			return "True"
		}
		return "False"
	case ir.Ref:
		return binderName(ir.Binder(expr))
	case ir.Negate:
		return "(-" + renderExpr(expr.Value) + ")"
	case ir.Binary:
		return fmt.Sprintf("(%s %s %s)", renderExpr(expr.Left), operators[expr.Op], renderExpr(expr.Right))
	case ir.Call:
		call := "_root_.GoLean." + symbolName(expr.Callee)
		if len(expr.Args) == 0 {
			return call
		}
		args := []string{call}
		for _, arg := range expr.Args {
			args = append(args, renderExpr(arg))
		}
		return "(" + strings.Join(args, " ") + ")"
	default:
		panic("unexpected IR expression")
	}
}

var operators = [...]string{
	ir.Add:          "+",
	ir.Subtract:     "-",
	ir.Multiply:     "*",
	ir.Equal:        "=",
	ir.NotEqual:     "≠",
	ir.Less:         "<",
	ir.LessEqual:    "≤",
	ir.Greater:      ">",
	ir.GreaterEqual: "≥",
}

func quoted(name string) string { return "«" + name + "»" }

func symbolName(symbol ir.Symbol) string {
	name := quoted(symbol.Package) + "." + quoted(symbol.File)
	if symbol.Dependency != "" {
		name += ".Dependencies." + quoted(symbol.Dependency)
	}
	return name + "." + quoted(symbol.Name)
}

func binderName(binder ir.Binder) string {
	return quoted(fmt.Sprintf("v%d_%s", binder.Index, binder.Name))
}
